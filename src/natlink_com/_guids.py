"""GUIDs for Dragon COM interfaces, service IDs, and marshaling registration."""

import ctypes
from ctypes import c_ulong, c_ushort, c_ubyte


class GUID(ctypes.Structure):
    """Raw GUID struct for ctypes COM calls (not comtypes.GUID)."""
    _fields_ = [
        ("Data1", c_ulong), ("Data2", c_ushort), ("Data3", c_ushort),
        ("Data4", c_ubyte * 8),
    ]
    def __init__(self, d1=0, d2=0, d3=0, d4=None):
        super().__init__()
        self.Data1, self.Data2, self.Data3 = d1, d2, d3
        if d4:
            for i, b in enumerate(d4):
                self.Data4[i] = b

